import java.io.*;
import java.util.*;

public class G_Iva_Pav {
    static class FastScanner {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        StringTokenizer st = new StringTokenizer("");
        String next() {
            while (!st.hasMoreTokens()) {
                try {
                    String line = br.readLine();
                    if (line == null) return null;
                    st = new StringTokenizer(line);
                } catch (IOException e) {
                    return null;
                }
            }
            return st.nextToken();
        }
        int nextInt() { return Integer.parseInt(next()); }
        long nextLong() { return Long.parseLong(next()); }
    }

    public static void main(String[] args) {
        FastScanner fs = new FastScanner();
        StringBuilder out = new StringBuilder();

        int t = fs.nextInt();
        //I had a very hard time understanding this problem, as I'm very new to bitwise operations in the context of CP.
        //The majority of this code was generated by AI, which walked me through it and now I have a much better understanding 
        //of this specific kind of problem and sparse tables as well. 
        while (t-- > 0) {
            int n = fs.nextInt();
            int[] a = new int[n + 1];
            for (int i = 1; i <= n; i++) a[i] = fs.nextInt();
            int[] lg = new int[n + 1];
            for (int i = 2; i <= n; i++) lg[i] = lg[i / 2] + 1;
            int LOG = lg[n] + 1;
            int[][] st = new int[LOG][n + 1];
            for (int i = 1; i <= n; i++) st[0][i] = a[i];
            for (int j = 1; j < LOG; j++) {
                for (int i = 1; i + (1 << j) - 1 <= n; i++) {
                    st[j][i] = st[j - 1][i] & st[j - 1][i + (1 << (j - 1))];
                }
            }
            int q = fs.nextInt();
            while (q-- > 0) {
                int l = fs.nextInt();
                int k = fs.nextInt();
                if (a[l] < k) {
                    out.append(-1).append(" ");
                    continue;
                }
                int lo = l, hi = n, ans = l;
                while (lo <= hi) {
                    int mid = (lo + hi) / 2;
                    int len = mid - l + 1;
                    int j = lg[len];
                    int val = st[j][l] & st[j][mid - (1 << j) + 1];
                    if (val >= k) {
                        ans = mid;
                        lo = mid + 1;
                    } else {
                        hi = mid - 1;
                    }
                }
                out.append(ans).append(" ");
            }
            out.append("\n");
        }
        System.out.print(out);
    }
}